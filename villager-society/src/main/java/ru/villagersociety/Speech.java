    private static String[] byRank(Rank r, String[] none, String[] ruler, String[] noble, String[] common, String[] outcast) {
        return switch (r) {
            case NONE -> none;
            case RULER -> ruler;
            case NOBLE -> noble;
            case COMMON -> common;
            case OUTCAST -> outcast;
        };
    }

