    // ---------- болтовня по рангам ----------
    public static String[] talk(Rank r) {
        return switch (r) {
            case NONE -> new String[]{
                    "%s, как думаешь, кто самый умный среди нас?",
                    "%s, тесновато в этой коробке под землёй, да?",
                    "Без начальства как-то странно. Может, выберем главного, %s?"
            };
            case RULER -> new String[]{
                    "%s, тебе не пора заняться делом?",
                    "Запомни, %s: порядок здесь — это я.",
                    "Хлеб любит тишину и моё имя, %s."
            };
            case NOBLE -> new String[]{
                    "%s, правитель сказал — значит, так и будет.",
                    "Я слежу, чтобы никто не ленился. И тебя это касается, %s.",
                    "%s, не путайся под ногами."
            };
            case COMMON -> new String[]{
                    "%s, у нас хоть хлеб остался?",
                    "Опять работа... Хоть бы поспать дали, %s.",
                    "Слава правителю... наверное, %s."
            };
            case OUTCAST -> new String[]{
                    "%s, всю ночь на ногах, глаза слипаются...",
                    "Почему меня всегда ставят последним, %s?",
                    "Хорошо хоть дети сыты, %s."
            };
        };
    }

    public static String[] reply(Rank r) {
        return switch (r) {
            case NONE -> new String[]{"Да, давай обсудим. Нужен порядок.", "Мне и так нормально, но голосовать согласен.", "Хм, интересный вопрос."};
            case RULER -> new String[]{"Молчать!", "Мне некогда слушать пустые речи."};
            case NOBLE -> new String[]{"Не нагружай меня своими заботами.", "Разговорчики. Работай."};
            case COMMON -> new String[]{"Ну, терпим...", "Что поделать. Живём."};
            case OUTCAST -> new String[]{"Да, господин...", "Хоть кто-то со мной говорит."};
        };
    }

    public static String[] mono(Rank r) {
        return switch (r) {
            case NONE -> new String[]{"Хорошая коробка. Только слишком тихо.", "Интересно, кто тут должен быть главным?"};
            case RULER -> new String[]{"Всё под контролем. Моим контролем.", "Кто-то должен командовать, и это я."};
            case NOBLE -> new String[]{"Правитель доволен — значит, и я доволен.", "Надо присмотреть за ленивыми."};
            case COMMON -> new String[]{"Так хочется выспаться.", "Лишь бы не попасть под горячую руку."};
            case OUTCAST -> new String[]{"Стоять всю ночь — не самая весёлая работа.", "Может, на следующем голосовании повезёт."};
        };
    }
